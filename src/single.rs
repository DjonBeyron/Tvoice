//! Одна копия программы на сеанс пользователя.
//!
//! Значок в трее и ярлык легко нажать дважды, а вторая копия — это второй глобальный
//! хоткей, второй whisper-server в памяти (и второй раз занятая видеопамять) и две
//! программы, печатающие в одно и то же поле ввода.
//!
//! Держим именованный мьютекс. Он живёт ровно столько, сколько процесс, и освобождается
//! ядром даже при аварийном завершении — в отличие от файла-метки, который после краша
//! пришлось бы удалять руками, иначе программа больше не запустилась бы вообще.
//!
//! Имя без префикса `Global\` — ограничение на сеанс: под другой учётной записью своя
//! копия поднимется нормально.

use windows::core::w;
use windows::Win32::Foundation::{
    CloseHandle, GetLastError, ERROR_ALREADY_EXISTS, LPARAM, WPARAM,
};
use windows::Win32::System::Threading::CreateMutexW;
use windows::Win32::UI::WindowsAndMessaging::{FindWindowW, PostMessageW};

/// Занять право быть единственной копией.
///
/// `true` — мы первая копия, можно поднимать GUI. `false` — копия уже работает, ей
/// отправлен запрос показать окно, и нам надо молча выйти.
pub fn claim() -> bool {
    match unsafe { CreateMutexW(None, true, w!("TVOICE_single_instance_v1")) } {
        Ok(handle) => {
            // Мьютекс уже существовал — создал его не мы, значит копия работает.
            if (unsafe { GetLastError() }) == ERROR_ALREADY_EXISTS {
                let _ = unsafe { CloseHandle(handle) };
                crate::logln!("single: копия уже запущена — показываю её окно и выхожу");
                wake_running();
                return false;
            }
            // Хэндл намеренно НЕ закрываем: право быть единственной копией держится ровно
            // пока он открыт, то есть до конца процесса. Закроет его ядро — в том числе
            // при аварийном завершении, поэтому «залипнуть» блокировка не может.
            true
        }
        Err(e) => {
            // Не смогли даже создать мьютекс — запрещать запуск на этом основании нельзя,
            // иначе программа перестанет запускаться из-за сбоя, к ней не относящегося.
            crate::logln!("single: не создать мьютекс ({e}) — проверка одной копии отключена");
            true
        }
    }
}

/// Попросить уже запущенную копию показать своё окно.
///
/// Ищем её скрытое окно трея по классу: наше собственное ещё не создано (трей поднимается
/// вместе с GUI, то есть после этой проверки), так что найдётся именно чужое.
fn wake_running() {
    unsafe {
        let Ok(hwnd) = FindWindowW(crate::tray::CLASS, windows::core::PCWSTR::null()) else {
            crate::logln!("single: окно запущенной копии не найдено (ещё поднимается?)");
            return;
        };
        if PostMessageW(hwnd, crate::tray::WM_SHOW_REQUEST, WPARAM(0), LPARAM(0)).is_err() {
            crate::logln!("single: запрос показать окно не доставлен");
        }
    }
}
